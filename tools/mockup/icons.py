# KMI/IRM ww code -> condition (identical to irm-kmi-ha IRM_KMI_TO_HA_CONDITION_MAP).
_WW = {
    0: "sunny", 1: "sunny", 3: "partlycloudy", 14: "cloudy", 15: "cloudy",
    18: "rainy", 21: "rainy", 4: "pouring", 6: "pouring", 16: "pouring", 19: "pouring",
    2: "lightning-rainy", 5: "lightning-rainy", 7: "lightning-rainy", 10: "lightning-rainy",
    13: "lightning-rainy", 17: "lightning-rainy", 8: "snowy-rainy", 9: "snowy-rainy",
    20: "snowy-rainy", 11: "snowy", 12: "snowy", 22: "snowy", 23: "snowy",
    24: "fog", 25: "fog", 26: "fog", 27: "fog",
}


def weather_condition(ww: int, night: bool) -> str:
    cond = _WW.get(int(ww), "cloudy")
    if night and cond == "sunny":
        return "clear-night"
    if night and cond == "partlycloudy":
        return "partlycloudy-night"
    return cond


def _check():
    assert set(ICONS9) == set(ICONS16), "ICONS9 must cover every ICONS16 condition"
    for name, rows in {**ICONS16, **{f"9:{k}": v for k, v in ICONS9.items()}, **ICONS7}.items():
        w = len(rows[0])
        assert all(len(r) == w for r in rows), name
        assert all(c == "." or c in PALETTE for r in rows for c in r), name


_check()
