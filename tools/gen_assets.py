"""Generate firmware C++ headers from the single sources of truth.

  python tools/gen_assets.py                 # icons only (offline)
  python tools/gen_assets.py --gtfs          # + line colours from official STIB/SNCB GTFS (keyless)

Writes:
  esphome/diele/diele_icons.h   pixel icons (tools/mockup/icons.py)
  esphome/diele/diele_lines.h   route_short_name -> brand colour / text colour / mode
"""
from __future__ import annotations

import csv
import io
import os
import sys
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "mockup"))
from icons import ICONS7, ICONS9, ICONS16, PALETTE  # noqa: E402

OUT = os.path.join(ROOT, "esphome", "diele")
GTFS = {
    "stib": "https://api-management-discovery-production.azure-api.net/api/gtfs/feed/stibmivb/static",
    "sncb": "https://api-management-discovery-production.azure-api.net/api/gtfs/feed/nmbssncb/static",
}
UA = {"User-Agent": "ha-diele-board asset generator (+https://github.com/Nosdave/ha-diele-board)"}


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def gen_icons():
    keys = sorted(PALETTE)
    lines = [
        "// GENERATED by tools/gen_assets.py from tools/mockup/icons.py - do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace diele {",
        "struct IconPal { char k; uint8_t r, g, b; };",
        "static const IconPal ICON_PALETTE[] = {",
    ]
    lines += [f"  {{'{k}', {PALETTE[k][0]}, {PALETTE[k][1]}, {PALETTE[k][2]}}}," for k in keys]
    lines += ["};", "struct Icon { const char *name; uint8_t w, h; const char *px; };"]
    for size, table in ((16, ICONS16), (9, ICONS9), (7, ICONS7)):
        lines.append(f"static const Icon ICONS{size}[] = {{")
        for name, rows in table.items():
            lines.append(f'  {{"{name}", {len(rows[0])}, {len(rows)}, "{"".join(rows)}"}},')
        lines.append("};")
    lines.append("}  // namespace diele")
    _write("diele_icons.h", lines)


def _fetch_routes(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=120) as r:
        z = zipfile.ZipFile(io.BytesIO(r.read()))
    with z.open("routes.txt") as f:
        return list(csv.DictReader(io.TextIOWrapper(f, "utf-8-sig")))


def gen_lines(routes_stib=None, routes_sncb=None):
    mode = {"0": 0, "1": 2, "3": 1, "2": 3}  # GTFS route_type -> Kind (TRAM, METRO, BUS, TRAIN)
    rows = {}
    for r in routes_stib or []:
        n = r["route_short_name"].strip()
        if n and n not in rows:
            rows[n] = (r.get("route_color") or "5A5A5A", (r.get("route_text_color") or "FFFFFF").upper() == "000000",
                       mode.get(r.get("route_type", "3"), 1))
    for r in routes_sncb or []:
        n = r["route_short_name"].strip()
        if n.startswith("S") and n[1:].isdigit() and n not in rows:
            col = r.get("route_color") or "016AB3"
            dark = col.upper() in ("FFCD00",)  # GTFS says white on S5 yellow; LED needs the outline style
            rows[n] = (col, dark or (r.get("route_text_color") or "FFFFFF").upper() == "000000", 3)
    for prod in ("IC", "L", "P", "EC", "EXT", "THA", "ICE", "EUR", "TRN"):
        rows.setdefault(prod, ("016AB3", False, 3))
    lines = [
        "// GENERATED by tools/gen_assets.py from official STIB/SNCB GTFS (route_short_name).",
        "// Light lines (brand text black) are drawn as outline badges on LEDs.",
        "#pragma once",
        "#include <cstdint>",
        "namespace diele {",
        "struct LineStyle { const char *name; uint32_t rgb; bool dark_text; uint8_t kind; };",
        "static const LineStyle LINE_STYLES[] = {",
    ]
    for n in sorted(rows, key=lambda s: (len(s), s)):
        col, dark, kind = rows[n]
        lines.append(f'  {{"{n}", 0x{col.upper()}, {"true" if dark else "false"}, {kind}}},')
    lines += ["};", "}  // namespace diele"]
    _write("diele_lines.h", lines)
    print(f"lines: {len(rows)}")


def _write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", name)


if __name__ == "__main__":
    gen_icons()
    if "--gtfs" in sys.argv:
        gen_lines(_fetch_routes(GTFS["stib"]), _fetch_routes(GTFS["sncb"]))
    elif "--routes" in sys.argv:  # offline: --routes <stib routes.txt> <sncb routes.txt>
        i = sys.argv.index("--routes")
        load = lambda p: list(csv.DictReader(open(p, encoding="utf-8-sig")))
        gen_lines(load(sys.argv[i + 1]), load(sys.argv[i + 2]))
